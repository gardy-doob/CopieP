#[link(name = "ApplicationServices", kind = "framework")]
extern "C" {
    fn AXIsProcessTrusted() -> bool;
    fn AXIsProcessTrustedWithOptions(options: CFDictionaryRef) -> bool;
}

/// Types posés par les gestionnaires de mots de passe pour demander aux
/// historiques de presse-papiers de ne rien enregistrer (nspasteboard.org).
const IGNORED_TYPES: [&str; 3] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

const CONCEALED_TYPE: &str = "org.nspasteboard.ConcealedType";

/// Touche « V » (même position en AZERTY et en QWERTY).
const KEY_V: u16 = 9;

fn pasteboard() -> Retained<NSPasteboard> {
    NSPasteboard::generalPasteboard()
}

/// Compteur de modifications du presse-papiers.
pub fn clipboard_change_count() -> Option<i64> {
    Some(pasteboard().changeCount() as i64)
}

/// Le contenu actuel demande à ne pas être enregistré (mot de passe…).
pub fn clipboard_is_concealed() -> bool {
    let Some(types) = pasteboard().types() else { return false };
    types.iter().any(|t| {
        let t = t.to_string();
        IGNORED_TYPES.contains(&t.as_str())
    })
}

/// Écrit un texte marqué « confidentiel » : les autres historiques de
/// presse-papiers ne l'enregistrent pas.
pub fn write_text_concealed(text: &str) -> bool {
    let pb = pasteboard();
    pb.clearContents();
    let ok = unsafe { pb.setString_forType(&NSString::from_str(text), NSPasteboardTypeString) };
    let _ = pb.setString_forType(&NSString::from_str(""), &NSString::from_str(CONCEALED_TYPE));
    ok
}

pub fn clear_clipboard() {
    pasteboard().clearContents();
}

/// Application au premier plan (là où il faudra coller).
pub fn frontmost_app_pid() -> Option<i32> {
    let app = NSWorkspace::sharedWorkspace().frontmostApplication()?;
    let pid = app.processIdentifier();
    (pid != std::process::id() as i32).then_some(pid)
}

#[allow(deprecated)]
pub fn activate_app(pid: i32) {
    if let Some(app) = NSRunningApplication::runningApplicationWithProcessIdentifier(pid) {
        app.activateWithOptions(NSApplicationActivationOptions::ActivateIgnoringOtherApps);
    }
}

/// Autorisation d'Accessibilité (nécessaire pour simuler ⌘V).
/// Avec `prompt`, macOS affiche sa fenêtre d'autorisation si besoin.
pub fn accessibility_trusted(prompt: bool) -> bool {
    unsafe {
        if !prompt {
            return AXIsProcessTrusted();
        }
        let key = CFString::new("AXTrustedCheckOptionPrompt");
        let options = CFDictionary::from_CFType_pairs(&[(key.as_CFType(), CFBoolean::true_value().as_CFType())]);
        AXIsProcessTrustedWithOptions(options.as_concrete_TypeRef())
    }
}

/// Simule ⌘V dans l'application au premier plan.
pub fn send_paste() -> bool {
    if !accessibility_trusted(true) {
        return false;
    }
    let Ok(source) = CGEventSource::new(CGEventSourceStateID::HIDSystemState) else { return false };
    let (Ok(down), Ok(up)) = (
        CGEvent::new_keyboard_event(source.clone(), KEY_V, true),
        CGEvent::new_keyboard_event(source, KEY_V, false),
    ) else {
        return false;
    };
    down.set_flags(CGEventFlags::CGEventFlagCommand);
    up.set_flags(CGEventFlags::CGEventFlagCommand);
    down.post(CGEventTapLocation::HID);
    up.post(CGEventTapLocation::HID);
    true
}

/// Demande Touch ID (ou le mot de passe de la session si Touch ID est
/// indisponible). Bloque jusqu'à la réponse.
pub fn authenticate(reason: &str) -> bool {
    let context = unsafe { LAContext::new() };
    unsafe {
        context.setLocalizedCancelTitle(Some(&NSString::from_str("Annuler")));
        context.setLocalizedFallbackTitle(Some(&NSString::from_str("Utiliser le mot de passe")));
    }
    let policy = LAPolicy::DeviceOwnerAuthentication;
    if unsafe { context.canEvaluatePolicy_error(policy) }.is_err() {
        return false;
    }

    let (tx, rx) = mpsc::channel::<bool>();
    let reply = RcBlock::new(move |success: Bool, _error: *mut NSError| {
        let _ = tx.send(success.as_bool());
    });
    unsafe {
        context.evaluatePolicy_localizedReason_reply(policy, &NSString::from_str(reason), &reply);
    }
    let result = rx.recv_timeout(Duration::from_secs(180)).unwrap_or(false);
    drop(context);
    result
}

/// Fenêtre « panneau » : visible sur tous les bureaux, y compris par-dessus
/// les apps en plein écran. À appeler sur le fil principal.
pub fn setup_panel(ns_window: *mut c_void) {
    if ns_window.is_null() {
        return;
    }
    let window: &NSWindow = unsafe { &*(ns_window as *const NSWindow) };
    window.setCollectionBehavior(
        NSWindowCollectionBehavior::CanJoinAllSpaces
            | NSWindowCollectionBehavior::FullScreenAuxiliary
            | NSWindowCollectionBehavior::IgnoresCycle,
    );
    // Au-dessus des fenêtres normales et des apps en plein écran.
    window.setLevel(101);
    window.setHidesOnDeactivate(false);
}
